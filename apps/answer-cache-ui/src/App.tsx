import { useEffect, useRef, useState, type FormEvent } from 'react';
import { AppLayout, useShellConnection } from 'shell';
import {
	DEFAULT_TTL_SECONDS, getAnswer, MAX_QUESTION_LENGTH, SAMPLE_QUESTIONS,
	type AnswerMode, type AnswerResult, type AnswerStage,
} from './answerCache';
import './answer-cache.css';

const stageLabels: Record<AnswerStage, string> = {
	'checking-cache': 'Checking Redis…',
	'generating-answer': 'Asking Gemini…',
	'loading-sample': 'Loading sample answer…',
	'saving-answer': 'Saving to Redis…',
};

const sourceLabels: Record<AnswerResult['source'], string> = {
	redis: 'Served from Redis',
	gemini: 'Generated by Gemini',
	sample: 'Loaded from samples',
};

type Run = AnswerResult & { number: number; question: string; finishedAt: number };
type Session = { total: number; hits: number; runs: Run[] };
const emptySession: Session = { total: 0, hits: 0, runs: [] };

function EntryLifetime({ run }: { run: Run }) {
	const [now, setNow] = useState(run.finishedAt);
	const end = run.ttlSeconds === null ? null : run.finishedAt + run.ttlSeconds * 1000;
	const remaining = end === null ? null : Math.max(0, Math.ceil((end - now) / 1000));

	const expired = remaining === 0;
	useEffect(() => {
		if (end === null || expired) return;
		const id = window.setInterval(() => setNow(Date.now()), 250);
		return () => window.clearInterval(id);
	}, [end, expired]);

	const progress = remaining === null ? 100 : (remaining / Math.max(run.ttlSeconds ?? 0, 1)) * 100;
	return (
		<div className="ac-lifetime" aria-live="off">
			<div className="ac-lifetime-label">
				<span>Time left in Redis</span>
				<strong>{remaining === null ? 'Unavailable' : remaining === 0 ? 'Expired' : `~${remaining}s`}</strong>
			</div>
			{remaining !== null && (
				<div className="ac-meter" aria-hidden="true">
					<span style={{ width: `${progress}%` }} />
				</div>
			)}
			{remaining === 0 && <p>Ask again to create a fresh entry.</p>}
		</div>
	);
}

function App() {
	const { client, isConnected } = useShellConnection();
	const [mode, setMode] = useState<AnswerMode>('sample');
	const [sampleQuestion, setSampleQuestion] = useState<string>(SAMPLE_QUESTIONS[0]);
	const [customQuestion, setCustomQuestion] = useState('');
	const [ttl, setTtl] = useState(DEFAULT_TTL_SECONDS);
	const [stage, setStage] = useState<AnswerStage | null>(null);
	const [error, setError] = useState('');
	const [session, setSession] = useState(emptySession);
	const pending = useRef(false);
	const question = mode === 'sample' ? sampleQuestion : customQuestion;
	const latest = session.runs[0];
	const busy = stage !== null;

	async function ask(event: FormEvent<HTMLFormElement>) {
		event.preventDefault();
		if (pending.current || !client || !isConnected || !question.trim()) return;

		pending.current = true;
		setError('');
		setStage('checking-cache');
		try {
			const result = await getAnswer(client, question, ttl, mode, setStage);
			const finishedAt = Date.now();
			setSession((previous) => {
				const number = previous.total + 1;
				const run = { ...result, number, question: question.trim(), finishedAt };
				return {
					total: number,
					hits: previous.hits + (result.cacheHit ? 1 : 0),
					runs: [run, ...previous.runs].slice(0, 5),
				};
			});
		} catch (problem) {
			setError(problem instanceof Error ? problem.message : 'The request failed. Check your connection and try again.');
		} finally {
			pending.current = false;
			setStage(null);
		}
	}

	return (
		<AppLayout>
			<main className="ac-page">
				<div className="ac-wrap">
					<header className="ac-header">
						<div className="ac-brand"><span aria-hidden="true" className="ac-mark"><i /><i /><i /></span> RocketRide / Redis</div>
						<span className="ac-connection" data-connected={isConnected}>
							<i aria-hidden="true" /> {isConnected ? 'Engine connected' : 'Engine disconnected'}
						</span>
					</header>
					<section className="ac-intro" aria-labelledby="ac-title">
						<div className="ac-eyebrow">LIVE CACHE DEMO</div>
						<h1 id="ac-title">Answer Cache</h1>
						<p>Ask a question, repeat it, then ask again after the entry expires. Watch Redis decide when an answer needs to be made fresh.</p>
					</section>

					<div className="ac-workbench">
						<form className="ac-panel ac-form" onSubmit={ask} aria-busy={busy}>
							<h2>Ask a question</h2>
							<fieldset className="ac-mode" disabled={busy}>
								<legend>Answer source on a miss</legend>
								<div className="ac-options">
									<label><input type="radio" name="ac-mode" checked={mode === 'sample'} onChange={() => setMode('sample')} /> Sample answers</label>
									<label><input type="radio" name="ac-mode" checked={mode === 'gemini'} onChange={() => setMode('gemini')} /> Gemini</label>
								</div>
							</fieldset>
							<p className="ac-note">{mode === 'sample' ? 'Uses prepared answers and live Redis. No model call.' : 'Calls Gemini only on a cache miss. Requires a configured API key.'}</p>

							<label className="ac-field" htmlFor="ac-question">Question</label>
							{mode === 'sample' ? (
								<select id="ac-question" value={sampleQuestion} disabled={busy} onChange={(event) => setSampleQuestion(event.target.value)}>
									{SAMPLE_QUESTIONS.map((item) => <option key={item}>{item}</option>)}
								</select>
							) : (
								<textarea id="ac-question" value={customQuestion} rows={3} maxLength={MAX_QUESTION_LENGTH} disabled={busy}
									onChange={(event) => setCustomQuestion(event.target.value)} placeholder="What would you like to know?" required />
							)}

							<label className="ac-field" htmlFor="ac-ttl">Lifetime for new entries</label>
							<select id="ac-ttl" value={ttl} disabled={busy} onChange={(event) => setTtl(Number(event.target.value))}>
								<option value={10}>10 seconds</option>
								<option value={30}>30 seconds</option>
								<option value={120}>2 minutes</option>
							</select>
							<button className="ac-ask" type="submit" disabled={busy || !isConnected || !question.trim()}>
								{stage ? stageLabels[stage] : 'Ask question'} <span aria-hidden="true">↗</span>
							</button>
							{!isConnected && <p className="ac-note">Connect to your local RocketRide development engine to ask.</p>}
							{error && <p className="ac-error" role="alert">{error}</p>}
						</form>

						<section className="ac-panel ac-result" aria-labelledby="ac-answer" aria-live="polite">
							<div className="ac-result-head">
								<h2 id="ac-answer">{latest ? 'Latest answer' : 'Answer'}</h2>
								{latest && <span className="ac-badge" data-hit={latest.cacheHit}>{latest.cacheHit ? 'Cache hit' : 'Cache miss'}</span>}
							</div>
							{latest ? (
								<>
									<p className="ac-question">{latest.question}</p>
									<p className="ac-answer">{latest.answer}</p>
									<div className="ac-meta">
										<span>{sourceLabels[latest.source]}</span>
										<span>{latest.elapsedMs} ms</span>
									</div>
									<EntryLifetime key={latest.number} run={latest} />
								</>
							) : (
								<div className="ac-empty">
									<span aria-hidden="true">⌁</span>
									<p>{stage ? stageLabels[stage] : 'Your answer will appear here.'}</p>
									<small>{stage ? 'Waiting for this request.' : 'Ask once to fill the cache. Ask again to read from it.'}</small>
								</div>
							)}
						</section>
					</div>

					<section className="ac-activity" aria-labelledby="ac-session">
						<div className="ac-activity-head">
							<h2 id="ac-session">This session</h2>
							<p>{session.total} {session.total === 1 ? 'request' : 'requests'} <span aria-hidden="true">/</span> {session.hits} Redis {session.hits === 1 ? 'hit' : 'hits'}
								{session.total > 0 && <> <span aria-hidden="true">/</span> {Math.round(session.hits / session.total * 100)}% hit rate</>}</p>
						</div>
						{session.runs.length > 0 && (
							<ol className="ac-history" reversed start={session.total}>
								{session.runs.map((run) => (
									<li key={run.number}>
										<span>{run.question}</span>
										<span className="ac-history-detail">{run.cacheHit ? 'Hit' : 'Miss'} · {sourceLabels[run.source]} · {run.elapsedMs} ms</span>
									</li>
								))}
							</ol>
						)}
					</section>
				</div>
			</main>
		</AppLayout>
	);
}

export default App;
